// Writes the files that are generated from the quiz format code, so they cannot drift from it:
//
//   public/ageno-quiz/        what the app serves: schema, templates, examples, and the skill as a zip
//                             (what claude.ai's Settings > Features takes)
//   skills/ageno-quiz-format/ the Agent Skill folder: SKILL.md, schema, validate.mjs (the app's own rules,
//                             bundled into one file) and examples
//
//   npm run build:format             # write them
//   npm run build:format -- --check  # fail if any file is missing or out of date (for CI and before commits)
import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { FULL_EXAMPLE, MINIMAL_EXAMPLE } from "@/lib/quiz-format/examples";
import { SKILL_NAME, skillMarkdown } from "@/lib/quiz-format/instructions";
import { buildJsonSchema } from "@/lib/quiz-format/json-schema";
import { makeZip } from "@/lib/quiz-format/zip";
import { csvTemplate, TEXT_TEMPLATE } from "@/lib/quiz-import/templates";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const json = (value: unknown) => JSON.stringify(value, null, 2) + "\n";

async function bundleValidator(): Promise<string> {
  const result = await build({
    entryPoints: [join(root, "scripts/format-cli.ts")],
    bundle: true,
    write: false,
    platform: "node",
    format: "esm",
    target: "node18",
    alias: { "@": root },
    legalComments: "none",
    logLevel: "silent",
  });
  const banner =
    "// Generated by `npm run build:format` from the Ageno Quiz source. Do not edit.\n" +
    "// Usage: node validate.mjs quiz.ageno.json [--json]\n";
  return banner + result.outputFiles[0].text;
}

async function files(): Promise<Record<string, string | Uint8Array>> {
  const schema = json(buildJsonSchema());
  const csv = csvTemplate();
  const minimal = json(MINIMAL_EXAMPLE);
  const full = json(FULL_EXAMPLE);
  const skill: Record<string, string> = {
    "SKILL.md": skillMarkdown(),
    "schema.json": schema,
    "validate.mjs": await bundleValidator(),
    "examples/minimal.ageno.json": minimal,
    "examples/full.ageno.json": full,
    "examples/template.csv": csv,
    "examples/template.txt": TEXT_TEMPLATE,
  };
  const out: Record<string, string | Uint8Array> = {
    "public/ageno-quiz/schema.json": schema,
    "public/ageno-quiz/template.csv": csv,
    "public/ageno-quiz/template.txt": TEXT_TEMPLATE,
    "public/ageno-quiz/example.ageno.json": full,
  };
  for (const [name, content] of Object.entries(skill)) out[`skills/${SKILL_NAME}/${name}`] = content;
  // The folder at the top of the zip, as claude.ai expects an uploaded skill.
  out[`public/ageno-quiz/${SKILL_NAME}.zip`] = makeZip(
    Object.entries(skill).map(([name, data]) => ({ name: `${SKILL_NAME}/${name}`, data }))
  );
  return out;
}

// Line endings differ between machines (git may check files out with CRLF); the content is what matters.
const normal = (text: string) => text.replace(/\r\n/g, "\n");

const same = (current: Buffer, content: string | Uint8Array): boolean =>
  typeof content === "string"
    ? normal(current.toString("utf8")) === normal(content)
    : Buffer.from(content).equals(current);

async function main() {
  const wanted = await files();
  const check = process.argv.includes("--check");
  const stale: string[] = [];
  for (const [path, content] of Object.entries(wanted)) {
    const full = join(root, path);
    const current = existsSync(full) ? readFileSync(full) : null;
    if (current !== null && same(current, content)) continue;
    if (check) {
      stale.push(path);
    } else {
      mkdirSync(dirname(full), { recursive: true });
      writeFileSync(full, content);
      console.log(`wrote ${path}`);
    }
  }
  if (check) {
    if (stale.length > 0) {
      console.error(`These generated files are missing or out of date:\n${stale.map((path) => `  ${path}`).join("\n")}\nRun \`npm run build:format\` and commit the result.`);
      process.exit(1);
    }
    console.log("Generated format files are up to date.");
  }
}

main().catch((cause) => {
  console.error(cause);
  process.exit(1);
});
